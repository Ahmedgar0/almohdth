export function useToast() {
  const [t, setT] = useState(null)
  useEffect(() => {
    if (!t) return
    const id = setTimeout(() => setT(null), 2800)
    return () => clearTimeout(id)
  }, [t])
  const show = useCallback((msg, bad = false) => setT({ msg, bad }), [])
  const node = t ? <div className={`toast ${t.bad ? 'bad' : ''}`} role="status">{t.msg}</div> : null
  return [node, show]
}

export function ImageModal({ src, onClose }) {
  useEffect(() => {
    if (!src) return
    const k = (e) => e.key === 'Escape' && onClose()
    window.addEventListener('keydown', k)
    return () => window.removeEventListener('keydown', k)
  }, [src, onClose])
  if (!src) return null
  return (
    <div className="overlay" onClick={onClose} role="dialog" aria-label="صورة الكتاب">
      <img src={src} alt="صورة الكتاب" />
    </div>
  )
}

export function Confirm({ open, title, body, confirmLabel, danger, onConfirm, onCancel }) {
  if (!open) return null
  return (
    <div className="overlay" role="dialog" aria-modal="true" onClick={onCancel}>
      <div className="dialog" onClick={(e) => e.stopPropagation()}>
        <h3>{title}</h3>
        {body && <p className="muted">{body}</p>}
        <div className="row" style={{ marginTop: 18, justifyContent: 'flex-end' }}>
          <button className="btn btn-quiet" onClick={onCancel}>تراجع</button>
          <button className={`btn ${danger ? 'btn-danger' : 'btn-primary'}`} onClick={onConfirm}>{confirmLabel}</button>
        </div>
      </div>
    </div>
  )
}

// تغيير كلمة مرور عضو الفريق لنفسه
export function PasswordDialog({ open, onClose, onSave }) {
  const [pw, setPw] = useState('')
  const [err, setErr] = useState('')
  const [busy, setBusy] = useState(false)
  if (!open) return null
  async function save(e) {
    e.preventDefault()
    if (pw.length < 8) return setErr('اجعلها 8 أحرف على الأقل')
    setBusy(true)
    try {
      await onSave(pw)
      setPw('')
      setErr('')
      onClose(true)
    } catch (x) {
      setErr(x.message)
    } finally {
      setBusy(false)
    }
  }
  return (
    <div className="overlay" role="dialog" aria-modal="true" onClick={() => onClose(false)}>
      <form className="dialog stack" onClick={(e) => e.stopPropagation()} onSubmit={save}>
        <h3>تغيير كلمة المرور</h3>
        <label className="field">
          <span className="label">كلمة المرور الجديدة</span>
          <input className="input ltr-in" type="password" autoComplete="new-password" value={pw} onChange={(e) => setPw(e.target.value)} autoFocus />
        </label>
        {err && <div className="notice bad">{err}</div>}
        <div className="row" style={{ justifyContent: 'flex-end' }}>
          <button type="button" className="btn btn-quiet" onClick={() => onClose(false)}>تراجع</button>
          <button className="btn btn-primary" disabled={busy}>حفظ</button>
        </div>
      </form>
    </div>
  )
}
